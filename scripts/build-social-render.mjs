#!/usr/bin/env node
// Bundle the explainer / Shorts pipeline for the render worker on the AI box (plan §4.5, P5).
//
//   node scripts/build-social-render.mjs        → worker/social-render/dist/pipeline.mjs
//
// The AI box runs worker/render-worker.mjs from a minimal node_modules (no tsx, no app tree). esbuild (already in the
// app's node_modules via tsx) resolves the `@/` alias and strips types; `@napi-rs/canvas` stays external and is
// installed on the box (`npm i @napi-rs/canvas` in ~/clipwaltz). Re-run and re-copy after any change under
// src/lib/explainer/** or src/lib/shorts/**.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "worker/social-render/dist/pipeline.mjs");
await build({
  entryPoints: [join(root, "worker/social-render/entry.ts")],
  outfile: out,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["@napi-rs/canvas"],
  alias: { "@": join(root, "src") },
  banner: { js: "// GENERATED by scripts/build-social-render.mjs — do not edit. Source: src/lib/explainer/**, src/lib/shorts/**" },
  logLevel: "warning",
});
console.log(`built ${out}`);
